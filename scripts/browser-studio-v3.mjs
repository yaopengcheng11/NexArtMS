// Disposable HTTP + browser fixture. Never writes to the user's project database.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {chromium} from 'playwright';
import {createStudioStore} from '../studio/db.mjs';
import {createJobRunner} from '../studio/jobs.mjs';
import {createStudioRouter} from '../studio/router.mjs';
import {DEFAULT_LIMITS} from '../studio/media.mjs';

const repo=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const root=fs.mkdtempSync(path.join(os.tmpdir(),'studio-browser-v3-'));
const store=createStudioStore(root);
const p=store.createProject({name:'全片人物分组验收',sceneMode:'proxy'});
const rev=()=>store.getProjectRow(p.id).revision;
const original=path.join(store.mediaDir(p.id),'fixture.mp4');
execFileSync('ffmpeg',['-v','error','-y','-f','lavfi','-i','testsrc2=size=320x240:rate=12:duration=2','-c:v','libx264','-pix_fmt','yuv420p',original],{windowsHide:true});
const ref=path.relative(root,original);
store.insertMedia(p.id,{id:'m-fixture',sha256:'a'.repeat(64),originalName:'fixture.mp4',originalRef:ref,proxyRef:ref,durationUs:2e6,width:320,height:240,rotation:0,timebase:'1/12',fpsNum:12,fpsDen:1,vfr:false,videoCodec:'h264',audioCodec:null,ptsCount:24,sizeBytes:fs.statSync(original).size,baseRevision:rev()});
store.replaceShots(p.id,[{id:'S01',startFrame:0,endFrameExclusive:12,startUs:0,endUs:1e6},{id:'S02',startFrame:12,endFrameExclusive:24,startUs:1e6,endUs:2e6}],'user',rev());
for(const [shotId,startFrame,endFrame] of [['S01',0,5],['S02',12,17],['S02',18,23]])store.insertTrack(p.id,shotId,{startFrame,endFrame,box:{x:.15,y:.1,w:.5,h:.8},provenance:'user'},rev());
const red=Array(128).fill(0),blue=Array(128).fill(0);red[0]=red[64]=1;blue[10]=blue[74]=1;
const sourceTracks=store.getTracks(p.id);
store.insertTrack(p.id,'S01',{startFrame:6,endFrame:11,box:{x:.15,y:.1,w:.5,h:.8},provenance:'user'},rev());
store.updateProject(p.id,{sourcePeopleCount:2},rev());
store.summarizePeople(p.id,rev(),new Map([[sourceTracks[0].id,red],[sourceTracks[1].id,red],[sourceTracks[2].id,blue]]));
const hero=store.createCharacter(p.id,{name:'主角组',color:'#28543F',scale:1.75},rev());
const jobs=createJobRunner(store,root,DEFAULT_LIMITS);
const router=createStudioRouter(store,root,{jobs});
const server=http.createServer(async(req,res)=>{
  if(await router(req,res))return;
  const pathname=new URL(req.url,'http://localhost').pathname;
  const file=pathname.startsWith('/assets/')?path.join(repo,'dist',pathname):path.join(repo,'dist','index.html');
  if(!file.startsWith(path.join(repo,'dist'))||!fs.existsSync(file)){res.writeHead(404);res.end();return;}
  res.writeHead(200,{'Content-Type':file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'text/html'});
  fs.createReadStream(file).pipe(res);
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
const checks=[];
const check=(name,pass)=>{checks.push({name,pass});if(!pass)throw new Error(name);};
try {
  await page.goto(`${base}/?project=${p.id}`);
  await page.getByRole('heading',{name:'全片角色'}).waitFor();
  check('主界面只显示两张角色卡',await page.locator('.studio-role-card').count()===2);
  check('未点击角色时不展示镜头',await page.locator('.studio-role-shots').count()===0);
  check('未知出场收进一个入口',await page.getByRole('button',{name:'待核对出场 · 1 段'}).isVisible());
  await page.getByRole('button',{name:'项目设置',exact:true}).click();
  await page.getByLabel('修改项目名称').fill('已设置的验收项目');
  await page.getByLabel('项目说明',{exact:true}).fill('相机与人物动作优先');
  await page.getByLabel('项目场景选项').selectOption('reconstruct');
  await page.screenshot({path:path.join(repo,'reports','studio-settings-v3.png')});
  await page.getByRole('button',{name:'保存项目设置'}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  check('设置持久化',store.getProjectRow(p.id).name==='已设置的验收项目'&&store.getProjectRow(p.id).scene_status==='pending');
  await page.locator('.studio-role-select input').nth(0).check();await page.locator('.studio-role-select input').nth(1).check();
  await page.getByLabel('目标代理角色组').selectOption(hero.id);
  await page.getByRole('button',{name:'应用分组'}).click();
  await page.getByText('代理组：主角组',{exact:true}).first().waitFor();
  check('不同素材人物共享一个代理组',store.getCast(p.id).bindings.length===3&&store.getCast(p.id).bindings.every(b=>b.character_id===hero.id));
  check('同一代理组仍保留两张素材角色卡',await page.locator('.studio-role-card').count()===2);
  await page.locator('#studio-people').screenshot({path:path.join(repo,'reports','studio-role-cards.png')});
  await page.getByRole('button',{name:'查看角色 1的镜头',exact:true}).click();
  check('点击角色才显示其镜头',await page.locator('.studio-role-shots button').count()===2);
  await page.locator('.studio-role-detail').screenshot({path:path.join(repo,'reports','studio-role-detail.png')});
  await page.getByRole('button',{name:'收起镜头',exact:true}).click();
  check('收起角色后镜头不再展开',await page.locator('.studio-role-shots').count()===0);
  await page.reload();await page.getByRole('heading',{name:'全片角色'}).waitFor();
  check('刷新保留分组',await page.getByText('代理组：主角组',{exact:true}).count()===2);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#studio-people').scrollIntoViewIfNeeded();
  check('390px没有横向溢出',await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(repo,'reports','studio-role-cards-mobile.png')});
  await page.getByRole('button',{name:'项目设置',exact:true}).click();
  check('删除需完整名称确认',await page.getByRole('button',{name:'永久删除项目'}).isDisabled());
  await page.getByLabel('输入项目名称确认删除').fill('已设置的验收项目');
  await page.getByRole('button',{name:'永久删除项目'}).click();
  await page.getByRole('heading',{name:'项目列表',exact:true}).waitFor();
  check('删除返回列表并清理临时数据',store.getProjectRow(p.id)===null&&!fs.existsSync(store.projectDir(p.id)));
  check('无页面脚本异常',errors.length===0);
}finally {
  await browser.close();await new Promise(resolve=>server.close(resolve));store.close();
  fs.rmSync(root,{recursive:true,force:true,maxRetries:5});
  const report={checks,errors,passed:checks.filter(c=>c.pass).length};
  fs.writeFileSync(path.join(repo,'reports','studio-role-cards-browser.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}
